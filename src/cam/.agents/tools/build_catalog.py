#!/usr/bin/env python3
"""Generate candidate_catalog.md from YAML. YAML is the only source of truth."""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

import yaml

REPO_ROOT = Path(__file__).resolve().parents[1]
SCHEMA_PATH = REPO_ROOT / "sources" / "catalog_schema.yaml"

BUCKET_LABEL = {
    "priority-curation": "priority-curation — CATLASS is SoT; write Case Card next",
    "cross-source-review": "cross-source-review — compare other repos before ingest",
    "knowledge-first": "knowledge-first — extract knowledge/, do not open a Case yet",
    "deferred": "deferred — hardware or v0.1 scope; wait",
}


def load_yaml(path: Path) -> dict:
    with path.open(encoding="utf-8") as fh:
        return yaml.safe_load(fh)


def sort_candidates(catalog: dict, schema: dict) -> list[dict]:
    bucket_rank = schema["bucket_rank"]
    return sorted(
        catalog["candidates"],
        key=lambda c: (
            bucket_rank[c["bucket"]],
            -int(c["scores"]["intrinsic_case_score"]),
            -int(c["scores"]["project_priority"]),
            c["id"],
        ),
    )


def validate(catalog: dict, schema: dict) -> list[str]:
    errors: list[str] = []
    enums = schema["enums"]
    weights = schema["scoring"]["intrinsic_formula"]

    if catalog.get("schema_version") != schema["schema_version"]:
        errors.append(
            f"schema_version {catalog.get('schema_version')!r} != frozen {schema['schema_version']!r}"
        )

    src = catalog.get("source") or {}
    for key in ("registry_ref", "commit", "branch", "scan_path"):
        if not src.get(key):
            errors.append(f"source.{key} missing")

    for cand in catalog.get("candidates") or []:
        cid = cand.get("id", "<no-id>")
        if cand.get("status") not in enums["status"]:
            errors.append(f"{cid}: bad status {cand.get('status')!r}")
        if cand.get("bucket") not in enums["bucket"]:
            errors.append(f"{cid}: bad bucket {cand.get('bucket')!r}")
        if cand.get("category") not in enums["category"]:
            errors.append(f"{cid}: bad category {cand.get('category')!r}")
        if cand.get("compute_engine") not in enums["compute_engine"]:
            errors.append(f"{cid}: bad compute_engine")
        if cand.get("communication_pattern") not in enums["communication_pattern"]:
            errors.append(f"{cid}: bad communication_pattern")
        for hw in cand.get("hardware") or []:
            if hw not in enums["hardware"]:
                errors.append(f"{cid}: bad hardware {hw!r}")
        for field, enum_name in (
            ("memory_pattern", "memory_pattern"),
            ("pipeline_pattern", "pipeline_pattern"),
        ):
            for item in cand.get(field) or []:
                if item not in enums[enum_name]:
                    errors.append(f"{cid}: bad {field} {item!r}")
        dtypes = cand.get("dtypes") or {}
        for key in schema["dtypes"]["keys"]:
            if key not in dtypes or not isinstance(dtypes[key], list):
                errors.append(f"{cid}: dtypes.{key} must be a list")
        if "dtype" in cand:
            errors.append(f"{cid}: legacy dtype field must be removed")
        scores = cand.get("scores") or {}
        expected = sum(int(scores[k]) * w for k, w in weights.items())
        if int(scores.get("intrinsic_case_score", -1)) != expected:
            errors.append(
                f"{cid}: intrinsic_case_score {scores.get('intrinsic_case_score')} != {expected}"
            )
        for tech in cand.get("key_techniques") or []:
            for ev in tech.get("evidence") or []:
                if ev.get("kind") not in enums["evidence_kind"]:
                    errors.append(f"{cid}: bad evidence_kind {ev.get('kind')!r}")
        for row in cand.get("competes_with") or []:
            if row.get("relation") not in enums["competes_relation"]:
                errors.append(f"{cid}: bad competes relation {row.get('relation')!r}")
            if row.get("review_state") not in enums["competes_review_state"]:
                errors.append(f"{cid}: bad review_state {row.get('review_state')!r}")
    return errors


def fmt_list(items) -> str:
    return ", ".join(items) if items else "—"


def fmt_dtypes(dtypes: dict) -> str:
    parts = []
    for key in ("input", "output", "accumulator", "scale"):
        vals = dtypes.get(key) or []
        if vals:
            parts.append(f"{key}: {', '.join(vals)}")
    return "; ".join(parts) if parts else "—"


def render_md(catalog: dict, schema: dict, catalog_path: Path) -> str:
    ordered = sort_candidates(catalog, schema)
    src = catalog["source"]
    lines: list[str] = []
    lines.append("<!-- Generated by tools/build_catalog.py. Do not edit. YAML is the source of truth. -->")
    lines.append("")
    lines.append(f"# Candidate Catalog (`{src['registry_ref']}`)")
    lines.append("")
    lines.append(f"- schema: `{catalog['schema_version']}`")
    lines.append(f"- registry_ref: `{src['registry_ref']}`")
    lines.append(f"- commit: `{src['commit']}`")
    lines.append(f"- branch: `{src['branch']}`")
    lines.append(f"- scan_path: `{src['scan_path']}` (Scout local path, not identity)")
    lines.append(f"- generated_from: `{catalog_path}`")
    lines.append("- Case Cards live under `cases/` when a candidate is `curated` or later")
    lines.append("")
    lines.append("## Sort")
    lines.append("")
    lines.append("`bucket_rank asc`, then `intrinsic_case_score desc`, then `project_priority desc`, then `id asc`.")
    lines.append("")
    lines.append("## Candidates")
    lines.append("")
    lines.append("| # | id | intrinsic/80 | project | status | bucket | HW | engine |")
    lines.append("| ---: | --- | ---: | ---: | --- | --- | --- | --- |")
    for i, cand in enumerate(ordered, 1):
        hw = fmt_list(cand.get("hardware") or [])
        lines.append(
            f"| {i} | `{cand['id']}` | {cand['scores']['intrinsic_case_score']} | "
            f"{cand['scores']['project_priority']} | {cand['status']} | {cand['bucket']} | "
            f"{hw} | {cand['compute_engine']} |"
        )
    lines.append("")

    current_bucket = None
    for cand in ordered:
        if cand["bucket"] != current_bucket:
            current_bucket = cand["bucket"]
            lines.append(f"## {BUCKET_LABEL[current_bucket]}")
            lines.append("")
        s = cand["scores"]
        sp = cand.get("source_path") or {}
        lines.append(f"### {cand['name']}")
        lines.append("")
        lines.append(f"- id: `{cand['id']}`")
        lines.append(f"- status: `{cand['status']}`")
        lines.append(f"- bucket: `{cand['bucket']}`")
        lines.append(
            f"- intrinsic: **{s['intrinsic_case_score']}**/80 "
            f"(R{s['representative']} O{s['optimization']} U{s['reusability']} "
            f"I{s['implementation']} D{s['documentation']})"
        )
        lines.append(f"- project_priority: **{s['project_priority']}**")
        lines.append(f"- category: `{cand['category']}`")
        lines.append(f"- algorithm: `{cand['algorithm']}`")
        lines.append(f"- hardware: {fmt_list(cand.get('hardware'))}")
        lines.append(f"- compute_engine: `{cand['compute_engine']}`")
        lines.append(f"- memory_pattern: {fmt_list(cand.get('memory_pattern'))}")
        lines.append(f"- pipeline_pattern: {fmt_list(cand.get('pipeline_pattern'))}")
        lines.append(f"- communication_pattern: `{cand['communication_pattern']}`")
        lines.append(f"- dtypes: {fmt_dtypes(cand.get('dtypes') or {})}")
        if cand.get("shape_characteristics"):
            lines.append(f"- shape: {cand['shape_characteristics']}")
        if cand.get("learn"):
            lines.append(f"- learn: {cand['learn']}")
        if cand.get("case_card"):
            lines.append(f"- case_card: `{cand['case_card']}`")
        if sp:
            lines.append("- source_path:")
            for k, v in sp.items():
                lines.append(f"  - {k}: `{v}`")
        lines.append("")
        lines.append("Key techniques:")
        lines.append("")
        for tech in cand.get("key_techniques") or []:
            lines.append(f"- {tech['claim']}")
            for ev in tech.get("evidence") or []:
                extra = f" — {ev['note']}" if ev.get("note") else ""
                path = f" `{ev['path']}`" if ev.get("path") else ""
                lines.append(f"  - evidence `{ev['kind']}`{path}{extra}")
            if tech.get("not"):
                lines.append(f"  - not: {tech['not']}")
        lines.append("")
        if cand.get("competes_with"):
            lines.append("competes_with:")
            lines.append("")
            for row in cand["competes_with"]:
                ref = f" `{row['ref']}`" if row.get("ref") else ""
                lines.append(
                    f"- `{row['source']}`{ref} — relation `{row['relation']}`, "
                    f"review `{row['review_state']}` — {row.get('why', '')}"
                )
            lines.append("")
        if cand.get("notes"):
            lines.append(f"notes: {cand['notes']}")
            lines.append("")
    if catalog.get("rejected"):
        lines.append("## Rejected (not in the 15)")
        lines.append("")
        for row in catalog["rejected"]:
            lines.append(f"- `{row['id']}`: {row.get('reason', '')}")
        lines.append("")
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "catalog",
        nargs="?",
        default=str(REPO_ROOT / "sources" / "scans" / "catlass" / "candidate_catalog.yaml"),
    )
    parser.add_argument("--check", action="store_true", help="validate only, do not write markdown")
    args = parser.parse_args()

    catalog_path = Path(args.catalog).resolve()
    schema = load_yaml(SCHEMA_PATH)
    catalog = load_yaml(catalog_path)
    errors = validate(catalog, schema)
    if errors:
        print("catalog validation failed:", file=sys.stderr)
        for err in errors:
            print(f"  - {err}", file=sys.stderr)
        return 1
    if args.check:
        print(f"OK {catalog_path} ({len(catalog['candidates'])} candidates)")
        return 0
    md_path = catalog_path.with_suffix(".md")
    md_path.write_text(render_md(catalog, schema, catalog_path), encoding="utf-8")
    print(f"wrote {md_path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
